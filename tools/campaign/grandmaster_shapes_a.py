def silhouette(level_id,size=500):
    key=ENTRIES[level_id][2]
    if key not in DRAWINGS: raise ValueError(f'Vector {level_id} {key} has not yet been authored')
    im=Image.new('1',(size,size)); draw=ImageDraw.Draw(im); s=size/100
    for op in DRAWINGS[key]:
        kind=op[0]
        if kind=='L':
            points,width=op[1:3]; fill=op[3] if len(op)>3 else 1
            draw.line([(round(x*s),round(y*s)) for x,y in points],fill=fill,width=max(1,round(width*s)),joint='curve')
            radius=width*s/2
            for x,y in points:
                draw.ellipse((round(x*s-radius),round(y*s-radius),round(x*s+radius),round(y*s+radius)),fill=fill)
        else:
            fill=op[2] if len(op)>2 else 1
            if kind=='P': draw.polygon([(round(x*s),round(y*s)) for x,y in op[1]],fill=fill)
            elif kind=='O': draw.ellipse(tuple(round(v*s) for v in op[1]),fill=fill)
            elif kind=='R': draw.rectangle(tuple(round(v*s) for v in op[1]),fill=fill)
            else: raise ValueError(kind)
    return im


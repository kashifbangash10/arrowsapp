def audit(output=None):
    out=Path(output or Path(__file__).resolve().parents[2]/'artifacts/campaign/grandmaster/shapes-a');out.mkdir(parents=True,exist_ok=True)
    records=[];seen={}
    for lid in sorted(AVAILABLE_IDS):
        mask=silhouette(lid,180);bbox=mask.getbbox();cropped=mask.crop(bbox).resize((128,128),Image.Resampling.NEAREST)
        digest=hashlib.sha256(cropped.tobytes()).hexdigest(); duplicate=seen.get(digest);seen[digest]=lid
        # Four-neighbour connected components; test close to runtime lattice resolution.
        small=mask.resize((96,96),Image.Resampling.NEAREST);remaining={(x,y) for y in range(96) for x in range(96) if small.getpixel((x,y))};sizes=[]
        while remaining:
            start=remaining.pop();stack=[start];count=1
            while stack:
                x,y=stack.pop()
                for p in ((x+1,y),(x-1,y),(x,y+1),(x,y-1)):
                    if p in remaining: remaining.remove(p);stack.append(p);count+=1
            sizes.append(count)
        records.append({'id':lid,'name':name_for(lid),'sha256':digest,'duplicateOf':duplicate,'components':sorted(sizes,reverse=True),'bbox':bbox})
    columns=5;cellw=230;cellh=250
    for batch in range(math.ceil(len(records)/25)):
        rows=records[batch*25:(batch+1)*25];sheet=Image.new('RGB',(columns*cellw,math.ceil(len(rows)/columns)*cellh),'#101318');d=ImageDraw.Draw(sheet)
        try:font=ImageFont.truetype('C:/Windows/Fonts/arial.ttf',17)
        except OSError:font=ImageFont.load_default()
        for n,row in enumerate(rows):
            x=(n%columns)*cellw;y=(n//columns)*cellh;im=silhouette(row['id'],205).convert('L');sheet.paste('white',(x+12,y+5,x+217,y+210),im)
            d.text((x+8,y+217),f"{row['id']} {row['name']}",fill='white',font=font)
            if len(row['components'])>1:d.text((x+8,y+237),f"PARTS {row['components']}",fill='#ff9c9c',font=font)
        sheet.save(out/f'outline-sheet-{batch+1}.png')
    (out/'audit.json').write_text(json.dumps(records,indent=2),encoding='utf-8')
    return records


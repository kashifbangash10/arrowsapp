class Pen:
    def __init__(self, image): self.d=ImageDraw.Draw(image); self.s=image.width/100
    def p(self, pts, fill=1): self.d.polygon([(x*self.s,y*self.s) for x,y in pts],fill=fill)
    def r(self, box, fill=1): self.d.rectangle([v*self.s for v in box],fill=fill)
    def e(self, box, fill=1): self.d.ellipse([v*self.s for v in box],fill=fill)
    def l(self, pts, width=6, fill=1):
        self.d.line([(x*self.s,y*self.s) for x,y in pts],fill=fill,width=max(1,round(width*self.s)),joint='curve')
        for x,y in (pts[0],pts[-1]): self.e((x-width/2,y-width/2,x+width/2,y+width/2),fill)
    def rr(self, box, radius=5, fill=1): self.d.rounded_rectangle([v*self.s for v in box],radius=radius*self.s,fill=fill)

def silhouette(level_id, size=500):
    if level_id not in NAMES: raise ValueError(level_id)
    im=Image.new('1',(size,size)); d=Pen(im)
    # Dispatch follows the editable category functions defined below.
    fn = globals().get('_draw_'+str((level_id-381)//10)) if level_id>=381 else globals().get('_draw_tableware')
    if fn is None: raise NotImplementedError(f'Silhouette {level_id} has not been authored yet')
    fn(level_id,d)
    return im

